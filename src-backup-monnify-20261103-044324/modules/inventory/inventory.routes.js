import { Router } from "express";
import authenticate from "../../middleware/auth.middleware.js";
import { tenantMiddleware } from "../../middleware/tenant.middleware.js";
import requirePermission from "../../middleware/permission.middleware.js";
import * as c from "./inventory.controller.js";
const router=Router(); router.use(authenticate,tenantMiddleware);
router.get("/",requirePermission("inventory","inventory","READ"),c.items);
router.get("/barcode/:barcode",requirePermission("inventory","inventory","READ"),c.itemByBarcode);
router.post("/items",requirePermission("inventory","inventory","CREATE"),c.createItem);
router.patch("/items/:id",requirePermission("inventory","inventory","UPDATE"),c.updateItem);
router.post("/verify",requirePermission("inventory","transactions","CREATE"),c.verify);
router.post("/transactions",requirePermission("inventory","transactions","CREATE"),c.transaction);
router.get("/transactions",requirePermission("inventory","transactions","READ"),c.transactions);
router.post("/transactions/:id/confirm",requirePermission("inventory","transactions","APPROVE"),c.confirm);
router.post("/transactions/:id/dispute",requirePermission("inventory","transactions","APPROVE"),c.dispute);
router.get("/ledger",requirePermission("inventory","ledger","READ"),c.ledger);
router.post("/receipts",requirePermission("inventory","ledger","CREATE"),c.receive);
router.post("/adjustments",requirePermission("inventory","ledger","UPDATE"),c.adjust);
router.get("/locations",requirePermission("inventory","locations","READ"),c.locations);
router.post("/locations",requirePermission("inventory","locations","CREATE"),c.createLocation);
router.get("/suppliers",requirePermission("inventory","suppliers","READ"),c.suppliers);
router.post("/suppliers",requirePermission("inventory","suppliers","CREATE"),c.createSupplier);
router.get("/me/transactions",requirePermission("inventory","transactions","READ"),c.employeeTransactions);
export default router;
